def check_licenses() -> None:
    # generated by gen_npm_notices.py (the app's npm tree changes with the code, so no pinned checksum)
    if not (LICENSES / "npm-licenses.txt").is_file():
        raise SystemExit("MISSING packaging/licenses/npm-licenses.txt: run `python packaging/gen_npm_notices.py`")
    for name, want in REQUIRED_LICENSES.items():
        f = LICENSES / name
        if not f.is_file():
            raise SystemExit("MISSING licence text packaging/licenses/%s: refusing to build a bundle without it" % name)
        got = sha256_of(f)
        if got != want:
            raise SystemExit("packaging/licenses/%s does not match its pinned checksum\n  expected %s\n  got      %s" % (name, want, got))


def check_requirements() -> None:
    r = subprocess.run([sys.executable, str(HERE / "hash_requirements.py"), "--check"])
    if r.returncode != 0:
        raise SystemExit("requirements-runtime.hashed.txt is stale or missing (see message above)")


def host_platform() -> str:
    m = platform.machine().lower()
    if sys.platform == "win32" and m in ("amd64", "x86_64"):
        return "win-x64"
    if sys.platform == "darwin" and m in ("arm64", "aarch64"):
        return "mac-arm64"
    raise SystemExit("Unsupported host %s/%s. Use --platform with --no-pip to cross-fetch." % (sys.platform, m))


def log(msg: str) -> None:
    print("[fetch_runtime] " + msg, flush=True)


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def download(spec: dict) -> Path:
    """Download into the cache (resume-free, atomic), verify checksum, return path."""
    CACHE.mkdir(parents=True, exist_ok=True)
    dest = CACHE / spec["file"]
    if dest.exists() and sha256_of(dest) == spec["sha256"]:
        log("cached  %s" % dest.name)
        return dest
    if dest.exists():
        log("cached file has wrong checksum, re-downloading: %s" % dest.name)
        dest.unlink()
    local = FFMPEG_LOCAL / spec["file"]
    if spec["url"].startswith(FFMPEG_BASE) and local.exists() and sha256_of(local) == spec["sha256"]:
        log("local build output %s" % local)
        shutil.copyfile(str(local), str(dest))
        return dest
    part = dest.with_suffix(dest.suffix + ".part")
    log("download %s" % spec["url"])
    req = urllib.request.Request(spec["url"], headers={"User-Agent": "reel-studio-packaging/1.0"})
    t0 = time.time()
    with urllib.request.urlopen(req, timeout=60) as r, open(part, "wb") as out:
        total = int(r.headers.get("Content-Length") or 0)
        done = 0
        last = 0.0
        while True:
            chunk = r.read(1 << 20)
            if not chunk:
                break
            out.write(chunk)
            done += len(chunk)
            if time.time() - last > 5:
                last = time.time()
                log("  %d / %d MB" % (done >> 20, total >> 20))
    got = sha256_of(part)
    if got != spec["sha256"]:
        part.unlink()
        raise SystemExit("CHECKSUM MISMATCH for %s\n  expected %s\n  got      %s" % (spec["file"], spec["sha256"], got))
    part.replace(dest)
    log("ok      %s (%.1f MB, %.0fs, sha256 verified)" % (dest.name, dest.stat().st_size / 1e6, time.time() - t0))
    return dest


def rmtree(p: Path) -> None:
    def onerr(func, path, exc):  # read-only files on Windows
        os.chmod(path, stat.S_IWRITE)
        func(path)
    if p.exists():
        shutil.rmtree(str(p), onerror=onerr)


def extract_tar(archive: Path, dest: Path) -> None:
    with tarfile.open(str(archive), "r:gz") as tf:
        try:
            tf.extractall(str(dest), filter="tar")  # py3.12+
        except TypeError:
            tf.extractall(str(dest))


def python_exe(rt: Path, plat: str) -> Path:
    return rt / "python" / ("python.exe" if plat == "win-x64" else "bin/python3")


def strip_python(rt: Path, plat: str) -> dict:
    """Remove caches, tests, docs, tcl/tk. Returns bytes saved. Safe: smoke test runs afterwards."""
    py = rt / "python"
    before = dir_size(py)
    removed = 0
    # stdlib dirs not needed by a headless engine
    stdlib = py / "Lib" if plat == "win-x64" else py / "lib" / "python3.11"
    for rel in ("test", "idlelib", "turtledemo", "tkinter", "lib2to3", "ensurepip", "__phello__"):
        p = stdlib / rel
        if p.is_dir():
            rmtree(p); removed += 1
        elif p.is_file():
            p.unlink(); removed += 1
    # tcl/tk runtime (names differ by release: tcl8.6 vs tcl9, itcl4.x, thread2.x ...) and the _tkinter module
    if plat == "win-x64":
        patterns = ["tcl", "DLLs/_tkinter.pyd", "DLLs/tcl*.dll", "DLLs/tk*.dll", "include"]
    else:  # POSIX is case-sensitive; do NOT use these globs on Windows ("lib/thread*" would match Lib/threading.py)
        patterns = ["lib/tcl*", "lib/tk*", "lib/itcl*", "lib/thread[0-9]*", "lib/pkgconfig", "lib/libtcl*", "lib/libtk*",
                    "lib/python3.11/lib-dynload/_tkinter*.so", "share", "include"]
    for pat in patterns:
        for p in py.glob(pat):
            if p.is_dir():
                rmtree(p); removed += 1
            elif p.exists():
                p.unlink(); removed += 1
    # package-management tooling is not needed at runtime (and pip's launchers embed build-machine paths)
    # onnxruntime ships model-conversion/quantization tooling (deep paths, unused: faster-whisper only runs the VAD model)
    for rel in ("site-packages/pip", "site-packages/setuptools", "site-packages/pkg_resources", "site-packages/_distutils_hack",
                "site-packages/onnxruntime/tools", "site-packages/onnxruntime/transformers", "site-packages/onnxruntime/quantization"):
        p = stdlib / rel
        if p.is_dir():
            rmtree(p); removed += 1
    # setuptools leaves a .pth that imports the (now removed) _distutils_hack: harmless-looking but prints
    # a traceback on EVERY interpreter start.
    for pth in (stdlib / "site-packages").glob("distutils-precedence.pth"):
        pth.unlink()
    for d in (stdlib / "site-packages").glob("*.dist-info"):
        if d.name.lower().startswith(("pip-", "setuptools-")):
            rmtree(d)
    # caches and test suites inside site-packages (never "tests" files imported at runtime)
    sp = stdlib / "site-packages"
    for dirpath, dirnames, filenames in os.walk(str(py)):
        for d in list(dirnames):
            if d == "__pycache__":
                rmtree(Path(dirpath) / d); dirnames.remove(d); removed += 1
            elif d in ("tests", "test") and str(sp) in dirpath:
                # only dirs literally named tests/test (numpy.testing etc. are kept)
                rmtree(Path(dirpath) / d); dirnames.remove(d); removed += 1
        for f in filenames:
            if f.endswith((".pyc", ".pyo", ".pdb", ".a")):  # .a: numpy's static dev libs, never used at runtime
                try:
                    (Path(dirpath) / f).unlink(); removed += 1
                except OSError:
                    pass
    # idle / 2to3 launchers need the removed tkinter / lib2to3; drop them and any symlink left dangling
    # (a dangling symlink breaks `xattr -cr`, codesign and notarization).
    for rel in ("bin/idle3", "bin/idle3.11", "bin/2to3", "bin/2to3-3.11"):
        p = py / rel
        if p.is_symlink() or p.exists():
            p.unlink(); removed += 1
    for dirpath, dirnames, filenames in os.walk(str(py)):
        for name in dirnames + filenames:
            p = os.path.join(dirpath, name)
            if os.path.islink(p) and not os.path.exists(p):
                os.unlink(p); removed += 1
    after = dir_size(py)
    return {"removed_items": removed, "saved_mb": round((before - after) / 1e6, 1), "final_mb": round(after / 1e6, 1)}


def dir_size(p: Path) -> int:
    total = 0
    for dirpath, _d, files in os.walk(str(p)):
        for f in files:
            try:
                total += os.path.getsize(os.path.join(dirpath, f))
            except OSError:
                pass
    return total


def install_python(plat: str, rt: Path, no_pip: bool) -> dict:
    spec = PLATFORMS[plat]["python"]
    arc = download(spec)
    rmtree(rt / "python")
    rt.mkdir(parents=True, exist_ok=True)
    log("extract python -> %s" % (rt / "python"))
    extract_tar(arc, rt)  # archive root dir is "python/"
    info = {"python": PBS_PY, "pbs_release": PBS_TAG}
    if no_pip:
        log("--no-pip: skipping dependency install")
        return info
    py = python_exe(rt, plat)
    env = dict(os.environ)
    for k in ("PYTHONHOME", "PYTHONPATH", "PYTHONSTARTUP", "PIP_REQUIRE_VIRTUALENV", "PIP_INDEX_URL", "PIP_EXTRA_INDEX_URL"):
        env.pop(k, None)
    env["PYTHONNOUSERSITE"] = "1"
    env["PIP_DISABLE_PIP_VERSION_CHECK"] = "1"
    env["PIP_NO_INPUT"] = "1"
    # --require-hashes: every wheel must match a SHA-256 in the file; --no-deps: the file is the complete closure.
    cmd = [str(py), "-I", "-m", "pip", "install", "--no-cache-dir", "--only-binary", ":all:", "--require-hashes", "--no-deps",
           "--no-warn-script-location", "-r", str(REQUIREMENTS_HASHED)]
    log("pip install --require-hashes -r %s" % REQUIREMENTS_HASHED.name)
    subprocess.run(cmd, check=True, env=env)
    freeze = subprocess.run([str(py), "-I", "-m", "pip", "freeze"], check=True, env=env, stdout=subprocess.PIPE, universal_newlines=True).stdout
    info["pip_freeze"] = sorted(l.strip() for l in freeze.splitlines() if l.strip())
    # Remove pip's script launchers: they embed absolute paths of THIS machine and would break after install.
    scripts = rt / "python" / ("Scripts" if plat == "win-x64" else "bin")
    for f in list(scripts.glob("*")) if scripts.is_dir() else []:
        n = f.name.lower()
        if plat == "win-x64" and n.endswith(".exe") and n not in ("python.exe",):
            f.unlink()
        elif plat == "mac-arm64" and f.is_file() and not n.startswith(("python", "idle", "pydoc")) and not f.is_symlink():
            try:
                head = f.read_bytes()[:2]
            except OSError:
                head = b""
            if head == b"#!":
                f.unlink()
    log("strip caches/tests")
    info["strip"] = strip_python(rt, plat)
    return info


def install_ffmpeg(plat: str, rt: Path) -> dict:
    spec = PLATFORMS[plat]
    exe = spec["exe"]
    out = rt / "ffmpeg"
    rmtree(out)
    out.mkdir(parents=True)
    arc = download(spec["ffmpeg_zip"])
    with zipfile.ZipFile(str(arc)) as z:
        for name in ("ffmpeg" + exe, "ffprobe" + exe, "BUILDINFO.txt"):
            with z.open(name) as src, open(str(out / name), "wb") as dst:
                shutil.copyfileobj(src, dst)
    if plat != "win-x64":
        for n in ("ffmpeg", "ffprobe"):
            (out / n).chmod(0o755)
    # The GPL v3 text the builds are licensed under comes from the committed, checksum-pinned copy (never the network),
    # on both platforms, so a bundle cannot be assembled without it.
    shutil.copyfile(str(LICENSES / "gpl-3.0.txt"), str(out / "LICENSE.txt"))
    for n in ("ffmpeg" + exe, "ffprobe" + exe, "LICENSE.txt"):
        if not (out / n).exists():
            raise SystemExit("missing " + n)
    ver = subprocess.run([str(out / ("ffmpeg" + exe)), "-hide_banner", "-version"], stdout=subprocess.PIPE, universal_newlines=True).stdout.splitlines()[0]
    log("ffmpeg ok: " + ver)
    return {"ffmpeg_version": ver}


def smoke(plat: str, rt: Path) -> None:
    py = python_exe(rt, plat)
    model = REPO / "engine" / "reelengine" / "models" / "face_detection_yunet_2023mar.onnx"
    code = (
        "import numpy, PIL, cv2, ctranslate2, faster_whisper, yt_dlp, jsonschema, pi_heif, sys, os\n"
        "pi_heif.register_heif_opener()\n"
        # pillow-heif's wheel bundles x265 (GPL-2.0+); it must never be in the bundle
        "try:\n"
        "    import pillow_heif\n"
        "    sys.exit('pillow_heif is installed: its wheel bundles GPL x265. Use pi-heif.')\n"
        "except ImportError:\n"
        "    pass\n"
        # the engine's placement code needs cv2.FaceDetectorYN to load the vendored model under this OpenCV
        "m = sys.argv[1] if len(sys.argv) > 1 else ''\n"
        "if m and os.path.exists(m):\n"
        "    d = cv2.FaceDetectorYN.create(m, '', (320, 320), 0.6, 0.3, 5000)\n"
        "    d.setInputSize((320, 240)); d.detect(numpy.zeros((240, 320, 3), numpy.uint8))\n"
        "    face = 'FaceDetectorYN ok'\n"
        "else:\n"
        "    face = 'FaceDetectorYN skipped (model not found)'\n"
        "print('smoke ok numpy', numpy.__version__, 'cv2', cv2.__version__, 'ct2', ctranslate2.__version__, 'pi_heif', pi_heif.__version__, face)\n")
    subprocess.run([str(py), "-I", "-c", code, str(model)], check=True)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--platform", choices=sorted(PLATFORMS), default=None)
    ap.add_argument("--force", action="store_true", help="rebuild even if runtime-manifest.json matches")
    ap.add_argument("--no-pip", action="store_true", help="download/extract only (needed when cross-fetching)")
    ap.add_argument("--ffmpeg-only", action="store_true", help="re-download/refresh only ffmpeg/ (keeps python/) and exit")
    ap.add_argument("--strip-only", action="store_true", help="re-apply the strip step to an existing runtime and exit")
    args = ap.parse_args()
    check_licenses()
    check_requirements()
    plat = args.platform or host_platform()
    if not args.no_pip and plat != host_platform():
        raise SystemExit("pip install must run on the target OS; pass --no-pip to cross-fetch")
    rt = RUNTIME / plat
    if args.ffmpeg_only:
        info = install_ffmpeg(plat, rt)
        mp = rt / "runtime-manifest.json"
        m = json.loads(mp.read_text(encoding="utf-8")) if mp.exists() else {}
        m.update(info)
        m.setdefault("fingerprint", {})["ffmpeg"] = [PLATFORMS[plat][k]["sha256"] for k in PLATFORMS[plat] if k.endswith("_zip")]
        mp.write_text(json.dumps(m, indent=2), encoding="utf-8")
        return
    if args.strip_only:
        log("strip: " + json.dumps(strip_python(rt, plat)))
        smoke(plat, rt)
        return
    req_hash = sha256_of(REQUIREMENTS_HASHED)
    manifest_path = rt / "runtime-manifest.json"
    fingerprint = {"pbs": PBS_TAG + PBS_PY, "req": req_hash, "licenses": [sha256_of(LICENSES / n) for n in sorted(REQUIRED_LICENSES)], "ffmpeg": [PLATFORMS[plat][k]["sha256"] for k in PLATFORMS[plat] if k.endswith("_zip")]}
    if manifest_path.exists() and not args.force and not args.no_pip:
        try:
            m = json.loads(manifest_path.read_text(encoding="utf-8"))
            if m.get("fingerprint") == fingerprint and (rt / "python").exists() and (rt / "ffmpeg").exists():
                log("runtime for %s is up to date (use --force to rebuild)" % plat)
                return
        except ValueError:
            pass
    t0 = time.time()
    manifest = {"platform": plat, "fingerprint": fingerprint, "built": time.strftime("%Y-%m-%dT%H:%M:%S")}
    manifest.update(install_python(plat, rt, args.no_pip))
    manifest.update(install_ffmpeg(plat, rt))
    if not args.no_pip:
        smoke(plat, rt)
    manifest["size_mb"] = {"python": round(dir_size(rt / "python") / 1e6, 1), "ffmpeg": round(dir_size(rt / "ffmpeg") / 1e6, 1)}
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    log("done in %.0fs: %s" % (time.time() - t0, json.dumps(manifest["size_mb"])))


if __name__ == "__main__":
    main()
