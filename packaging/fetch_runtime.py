#!/usr/bin/env python3
"""Fetch and assemble the bundled runtime for one platform.

    python packaging/fetch_runtime.py                 # host platform (win-x64 or mac-arm64)
    python packaging/fetch_runtime.py --force         # rebuild even if up to date
    python packaging/fetch_runtime.py --platform mac-arm64 --no-pip   # download only (cross-fetch)

Result, gitignored:

    packaging/cache/                       downloaded archives (checksum verified, reused)
    packaging/runtime/<platform>/
        python/                            python-build-standalone CPython 3.11 + pinned deps (hash-checked)
        ffmpeg/ffmpeg[.exe], ffprobe[.exe] static ffmpeg + license texts
        runtime-manifest.json              what was installed (versions, hashes)

Stdlib only and Python 3.8+ compatible, so it also runs under the macOS system python3.
Every download is verified against a SHA-256 pinned below (or the project's published
checksum file). If a checksum differs the script stops; it never "just uses" the file.
"""
