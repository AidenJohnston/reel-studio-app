#!/usr/bin/env python3
"""Regenerate packaging/licenses/npm-licenses.txt: the verbatim licence files of every npm package that ships.

    npm install --ignore-scripts          # at the repo root, so node_modules exists
    python packaging/gen_npm_notices.py   # rewrites packaging/licenses/npm-licenses.txt

Ships = the production dependency tree of the app (`npm ls --all --omit=dev`, which includes @reelstudio/ai and the
Anthropic SDK it loads at run time) + the front-end libraries that vite bundles into the window (react, react-dom,
scheduler: they are devDependencies only because bundling happens at build time). Exits non-zero if a package has no
licence file or if its declared licence is not on the permissive allow-list, so a GPL/AGPL/non-commercial dependency
cannot slip in unnoticed.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "licenses" / "npm-licenses.txt"
BUNDLED_FRONTEND = ["react", "react-dom", "scheduler"]
ALLOWED = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Unlicense", "0BSD", "CC0-1.0"}
# Packages whose npm tarball carries no licence file: (SPDX shown, file to use instead).
NO_FILE = {"standardwebhooks": "licenses/npm-extra/standardwebhooks-LICENSE.txt"}


def walk(node: dict, seen: set) -> None:
    for name, child in (node.get("dependencies") or {}).items():
        if name.startswith("@reelstudio/"):
            walk(child, seen)
            continue
        seen.add(name)
        walk(child, seen)


def main() -> None:
    npm = shutil.which("npm.cmd") or shutil.which("npm")
    tree = json.loads(subprocess.run([npm, "ls", "--all", "--omit=dev", "--json"], cwd=str(REPO), stdout=subprocess.PIPE,
                                     universal_newlines=True).stdout)
    names: set = set(BUNDLED_FRONTEND)
    walk(tree, names)
    problems, parts = [], []
    for name in sorted(names):
        pkg_dir = REPO / "node_modules" / name
        if not pkg_dir.is_dir():  # an optional peer that is not installed (zod for the Anthropic SDK) does not ship
            print("skipping %s: not installed (optional peer)" % name)
            continue
        meta = json.loads((pkg_dir / "package.json").read_text(encoding="utf-8"))
        lic = meta.get("license")
        if lic not in ALLOWED:
            problems.append("%s: licence %r is not on the permissive allow-list" % (name, lic))
        text = None
        for cand in ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license"):
            if (pkg_dir / cand).is_file():
                text = (pkg_dir / cand).read_text(encoding="utf-8", errors="replace")
                break
        if text is None and name in NO_FILE:
            text = (Path(__file__).resolve().parent / NO_FILE[name]).read_text(encoding="utf-8")
        if text is None:
            problems.append("%s: no licence file" % name)
            continue
        parts.append("=" * 78 + "\n%s %s  (%s)\n%s\n" % (name, meta["version"], lic, meta.get("homepage") or meta.get("repository", "")) +
                     "=" * 78 + "\n" + text.strip() + "\n")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        sys.exit(1)
    header = ("Licences of the npm packages inside Reel Studio (generated by packaging/gen_npm_notices.py).\n"
              "Production dependencies of the app + the front-end libraries bundled into the window.\n\n")
    OUT.write_text(header + "\n".join(parts), encoding="utf-8", newline="\n")
    print("wrote %s (%d packages)" % (OUT, len(parts)))


if __name__ == "__main__":
    main()
