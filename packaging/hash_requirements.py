#!/usr/bin/env python3
"""Generate packaging/requirements-runtime.hashed.txt: the ONE file fetch_runtime.py installs.
Also generates packaging/requirements-opencv-build.hashed.txt, the build tools build_opencv_mac.py installs.

    python packaging/hash_requirements.py            # (re)generate both
    python packaging/hash_requirements.py --check    # exit 1 if either is stale (fetch_runtime.py runs this)

Single source of truth for Python dependencies:

    engine/requirements.txt             the engine's own exact pins (what its tests ran against)
    packaging/requirements-extra.txt    packages the BUNDLE adds on top (pi-heif)

This script copies those pins verbatim (markers included) and adds, to every pin, the SHA-256 of every
usable wheel PyPI lists for that exact version. fetch_runtime.py then runs
`pip install --require-hashes --no-deps`, so a tampered or substituted wheel cannot be installed and the
bundle cannot drift from the engine's pins. The header records a digest of the two inputs; --check fails when
either input changed after the last generation.

Stdlib only. Needs network (PyPI JSON API) when generating, not when checking.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
ENGINE_REQ = REPO / "engine" / "requirements.txt"
EXTRA_REQ = HERE / "requirements-extra.txt"
OUT = HERE / "requirements-runtime.hashed.txt"
OPENCV_BUILD_REQ = HERE / "requirements-opencv-build.txt"
OPENCV_BUILD_OUT = HERE / "requirements-opencv-build.hashed.txt"
# (generated file, its inputs, the header lines that say where its pins come from and who installs it)
TARGETS = [
    (OUT, (ENGINE_REQ, EXTRA_REQ), [
        "# Sources of truth: engine/requirements.txt (the engine's pins) + packaging/requirements-extra.txt (bundle-only extras).",
        "# fetch_runtime.py installs this with `pip install --require-hashes --no-deps`.",
    ]),
    (OPENCV_BUILD_OUT, (OPENCV_BUILD_REQ,), [
        "# Source of truth: packaging/requirements-opencv-build.txt (tools that compile OpenCV for macOS; never shipped).",
        "# build_opencv_mac.py installs this into its build venv with `pip install --require-hashes --no-deps`.",
    ]),
]

PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;]+)\s*(;.*)?$")
# Keep wheels that can be installed on a supported target: CPython 3.11 (or abi3 / pure python) on
# Windows x64 or macOS (arm64, x86_64, universal2).
WHEEL = re.compile(r"^(?P<name>.+?)-(?P<ver>[^-]+)(-(?P<build>\d[^-]*))?-(?P<py>[^-]+)-(?P<abi>[^-]+)-(?P<plat>[^-]+)\.whl$")


def digest_inputs(inputs) -> str:
    h = hashlib.sha256()
    for p in inputs:
        h.update(p.name.encode() + b"\0" + p.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return h.hexdigest()


def read_pins(path: Path) -> list[tuple[str, str, str]]:
    pins = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = PIN.match(line)
        if not m:
            raise SystemExit("%s: not an exact pin (name==version): %r" % (path.name, line))
        pins.append((m.group(1), m.group(2), (m.group(3) or "").strip()))
    return pins


def wheel_ok(filename: str) -> bool:
    m = WHEEL.match(filename)
    if not m:
        return False
    py, abi, plat = m.group("py"), m.group("abi"), m.group("plat")
    py_ok = ("cp311" in py) or (abi == "abi3" and "cp3" in py) or (abi == "none" and "py3" in py)
    plat_ok = plat == "any" or "win_amd64" in plat or plat.startswith("macosx_")
    if plat.startswith("macosx_") and not any(a in plat for a in ("arm64", "x86_64", "universal2")):
        plat_ok = False
    return py_ok and plat_ok


def fetch_hashes(name: str, ver: str) -> list[str]:
    url = "https://pypi.org/pypi/%s/%s/json" % (name, ver)
    req = urllib.request.Request(url, headers={"User-Agent": "reel-studio-packaging/1.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = json.load(r)
    hashes = sorted({f["digests"]["sha256"] for f in data["urls"]
                     if f["packagetype"] == "bdist_wheel" and wheel_ok(f["filename"])})
    if not hashes:
        raise SystemExit("no installable wheel on PyPI for %s==%s" % (name, ver))
    return hashes


def generate(inputs, header: list) -> str:
    pins = [pin for path in inputs for pin in read_pins(path)]
    seen = set()
    lines = ["# GENERATED by `python packaging/hash_requirements.py`. DO NOT EDIT BY HAND."] + header + [
        "# inputs-sha256: " + digest_inputs(inputs),
        "",
    ]
    for name, ver, marker in pins:
        if "python_full_version >= '3.12'" in marker or "emscripten" in marker and "!=" not in marker:
            continue  # the bundle is CPython 3.11 on win32/darwin: these pins can never apply (and have no cp311 wheel)
        key = (name.lower(), ver, marker)
        if key in seen:
            continue
        seen.add(key)
        hs = fetch_hashes(name, ver)
        print("  %-28s %-14s %d wheel hashes" % (name, ver, len(hs)), file=sys.stderr)
        head = "%s==%s" % (name, ver) + (" %s" % marker if marker else "")
        lines.append(head + " \\\n" + " \\\n".join("    --hash=sha256:" + h for h in hs))
    return "\n".join(lines) + "\n"


def check() -> bool:
    ok = True
    for out, inputs, _header in TARGETS:
        if not out.exists():
            print("hash_requirements: %s is missing; run `python packaging/hash_requirements.py`" % out.name, file=sys.stderr)
            ok = False
            continue
        m = re.search(r"^# inputs-sha256: ([0-9a-f]{64})$", out.read_text(encoding="utf-8"), re.M)
        if not m or m.group(1) != digest_inputs(inputs):
            print("hash_requirements: %s is STALE (%s changed).\n"
                  "Run `python packaging/hash_requirements.py` and commit the result."
                  % (out.name, " or ".join(p.name for p in inputs)), file=sys.stderr)
            ok = False
    return ok


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        sys.exit(0 if check() else 1)
    for out, inputs, header in TARGETS:
        out.write_text(generate(inputs, header), encoding="utf-8", newline="\n")
        print("wrote %s" % out, file=sys.stderr)


if __name__ == "__main__":
    main()
